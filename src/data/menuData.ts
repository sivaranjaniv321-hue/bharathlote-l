import { DishVisualMotif, MainCategory, MenuItem } from '../types';

interface RawDishInput {
  name: string;
  price: number;
  originalPrice?: number;
  discountLabel?: string;
  isVeg: boolean;
  rating: number;
  category: MainCategory;
  tags?: MainCategory[];
  sectionGroup: string;
  shortDescription: string;
  fullDescription?: string;
  motif: DishVisualMotif;
  accentTone: string;
  isPopular?: boolean;
  isDailySpecial?: boolean;
  imageSrc?: string;
  searchAliases?: string[];
}

function toSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function buildDish(input: RawDishInput): MenuItem {
  const slug = toSlug(input.name);
  const tags = input.tags
    ? Array.from(new Set([input.category, ...input.tags]))
    : [input.category];

  return {
    id: slug,
    slug,
    name: input.name,
    shortDescription: input.shortDescription,
    fullDescription:
      input.fullDescription ??
      `${input.shortDescription} Prepared fresh to order in the Bharath Delights kitchen using authentic Tamil Nadu spices and traditional cooking techniques.`,
    price: input.price,
    originalPrice: input.originalPrice,
    discountLabel: input.discountLabel,
    category: input.category,
    tags,
    sectionGroup: input.sectionGroup,
    isVeg: input.isVeg,
    rating: input.rating,
    isPopular: input.isPopular,
    isDailySpecial: input.isDailySpecial,
    imageSrc: input.imageSrc,
    expectedImagePath: `images/${slug}.jpg`,
    motif: input.motif,
    accentTone: input.accentTone,
    searchAliases: input.searchAliases,
  };
}

